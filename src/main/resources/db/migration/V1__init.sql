CREATE INDEX idx_sensor_reading_room_measured ON sensor_reading (room_id, measured_at);

COMMENT ON TABLE sensor_reading IS '실내 센서 측정값';
COMMENT ON COLUMN sensor_reading.id IS '측정 ID';
COMMENT ON COLUMN sensor_reading.room_id IS '공간 ID';
COMMENT ON COLUMN sensor_reading.co2 IS 'CO2 농도 (ppm)';
COMMENT ON COLUMN sensor_reading.temp IS '온도 (℃), 센서 실패 시 NULL';
COMMENT ON COLUMN sensor_reading.humidity IS '습도 (%), 센서 실패 시 NULL';
COMMENT ON COLUMN sensor_reading.measured_at IS '측정 시각 (KST)';


