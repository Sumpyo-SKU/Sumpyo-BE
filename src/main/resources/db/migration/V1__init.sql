-- =========================================================
-- complaint : 민원
-- =========================================================
CREATE TABLE complaint (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id           BIGINT       NOT NULL,
    categories        VARCHAR(100) NOT NULL,
    content           VARCHAR(500),
    status            VARCHAR(15)  NOT NULL DEFAULT 'RECEIVED',
    co2_snapshot      INT,
    temp_snapshot     DECIMAL(4, 1),
    humidity_snapshot INT,
    client_hash       VARCHAR(64),
    created_at        TIMESTAMP    NOT NULL,
    CONSTRAINT fk_complaint_room FOREIGN KEY (room_id) REFERENCES room (id),
    CONSTRAINT ck_complaint_categories CHECK (
        categories ~ '^(STUFFY|HOT|COLD|HUMID|SMELL|BROKEN)(,(STUFFY|HOT|COLD|HUMID|SMELL|BROKEN))*$'),
    CONSTRAINT ck_complaint_status CHECK (status IN ('RECEIVED', 'IN_PROGRESS', 'DONE'))
);
CREATE INDEX idx_complaint_room_created ON complaint (room_id, created_at);

COMMENT ON TABLE complaint IS '민원';
COMMENT ON COLUMN complaint.id IS '민원 ID';
COMMENT ON COLUMN complaint.room_id IS '공간 ID';
COMMENT ON COLUMN complaint.categories IS '민원 분류, 쉼표 구분 (STUFFY: 답답함, HOT: 더움, COLD: 추움, HUMID: 습함, SMELL: 냄새, BROKEN: 고장)';
COMMENT ON COLUMN complaint.content IS '민원 내용';
COMMENT ON COLUMN complaint.status IS '처리 상태 (RECEIVED: 접수, IN_PROGRESS: 처리 중, DONE: 완료)';
COMMENT ON COLUMN complaint.co2_snapshot IS '접수 시점 CO2 (ppm)';
COMMENT ON COLUMN complaint.temp_snapshot IS '접수 시점 온도 (℃)';
COMMENT ON COLUMN complaint.humidity_snapshot IS '접수 시점 습도 (%)';
COMMENT ON COLUMN complaint.client_hash IS '익명 신고자 식별 해시 (중복 신고 방지)';
COMMENT ON COLUMN complaint.created_at IS '접수 시각 (KST)';


-- =========================================================
-- action : 환기/냉난방 조치 (예측·민원 기반 추천과 처리 결과)
-- =========================================================
CREATE TABLE action (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    room_id            BIGINT      NOT NULL,
    source             VARCHAR(15) NOT NULL,
    prediction_id      BIGINT,
    complaint_id       BIGINT,
    class_schedule_id  BIGINT,
    recommend          VARCHAR(10) NOT NULL,
    metric             VARCHAR(10),
    predicted_value    INT,
    threshold          INT,
    expected_at        TIMESTAMP,
    summary            VARCHAR(200),
    co2_before         INT,
    expected_co2_after INT,
    actual_co2_after   INT,
    window_opened_at   TIMESTAMP,
    window_closed_at   TIMESTAMP,
    ac_on_at           TIMESTAMP,
    ac_target_temp     INT,
    member_id          BIGINT,
    status             VARCHAR(15) NOT NULL DEFAULT 'PENDING',
    created_at         TIMESTAMP   NOT NULL,
    completed_at       TIMESTAMP,
    CONSTRAINT fk_action_room FOREIGN KEY (room_id) REFERENCES room (id),
    CONSTRAINT fk_action_prediction FOREIGN KEY (prediction_id) REFERENCES prediction (id),
    CONSTRAINT fk_action_complaint FOREIGN KEY (complaint_id) REFERENCES complaint (id),
    CONSTRAINT fk_action_class_schedule FOREIGN KEY (class_schedule_id) REFERENCES class_schedule (id),
    CONSTRAINT fk_action_member FOREIGN KEY (member_id) REFERENCES member (id),
    CONSTRAINT ck_action_source CHECK (source IN ('PREDICTION', 'COMPLAINT')),
    CONSTRAINT ck_action_recommend CHECK (recommend IN ('OPEN', 'CLOSE')),
    CONSTRAINT ck_action_metric CHECK (metric IN ('CO2', 'HUMIDITY', 'TEMP')),
    CONSTRAINT ck_action_status CHECK (status IN ('PENDING', 'CHECKED', 'IN_PROGRESS', 'DONE', 'EXPIRED'))
);
CREATE INDEX idx_action_room_status ON action (room_id, status);
CREATE INDEX idx_action_prediction ON action (prediction_id);
CREATE INDEX idx_action_complaint ON action (complaint_id);
CREATE INDEX idx_action_class_schedule ON action (class_schedule_id);
CREATE INDEX idx_action_member ON action (member_id);

COMMENT ON TABLE action IS '환기/냉난방 조치 (예측·민원 기반 추천과 처리 결과)';
