COMMENT ON COLUMN action.source IS '발생 원인 (PREDICTION: 예측, COMPLAINT: 민원)';
COMMENT ON COLUMN action.prediction_id IS '원인 예측 ID';
COMMENT ON COLUMN action.complaint_id IS '원인 민원 ID';
COMMENT ON COLUMN action.class_schedule_id IS '관련 수업 시간표 ID';
COMMENT ON COLUMN action.recommend IS '추천 조치 (OPEN: 창문 열기, CLOSE: 창문 닫기)';
COMMENT ON COLUMN action.metric IS '기준 지표 (CO2, HUMIDITY, TEMP)';
COMMENT ON COLUMN action.predicted_value IS '예측값';
COMMENT ON COLUMN action.threshold IS '기준값';
COMMENT ON COLUMN action.expected_at IS '기준 초과 예상 시각 (KST)';
COMMENT ON COLUMN action.summary IS '조치 요약 문구';
COMMENT ON COLUMN action.co2_before IS '조치 전 CO2 (ppm)';
