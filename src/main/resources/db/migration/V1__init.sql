COMMENT ON COLUMN action.member_id IS '처리 담당자 ID';
COMMENT ON COLUMN action.status IS '처리 상태 (PENDING: 대기, CHECKED: 확인, IN_PROGRESS: 처리 중, DONE: 완료, EXPIRED: 만료)';
