-- V1__init.sql : 숨표 전체 스키마
-- 시간 컬럼은 모두 TIMESTAMP(타임존 없음)이며 KST 값을 그대로 저장한다.

-- 운영 DB에는 JPA(ddl-auto)가 만든 sensor_reading(room_id VARCHAR '517')이 있다.
-- 데이터 보존을 위해 legacy로 이름만 바꾸고, 이관은 V3에서 한다. 새 DB에서는 아무 일도 일어나지 않는다.
ALTER TABLE IF EXISTS sensor_reading RENAME TO sensor_reading_legacy;
-- 인덱스 이름은 스키마 전역이라 새 테이블과 겹치지 않도록 legacy 쪽 이름도 바꿔 둔다.
ALTER INDEX IF EXISTS sensor_reading_pkey RENAME TO sensor_reading_legacy_pkey;
ALTER INDEX IF EXISTS idx_room_time RENAME TO idx_sensor_reading_legacy_room_time;


-- =========================================================
-- building : 건물
-- =========================================================
CREATE TABLE building (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(30) NOT NULL,
    max_floor INT,
    CONSTRAINT uk_building_name UNIQUE (name)
);

COMMENT ON TABLE building IS '건물';
COMMENT ON COLUMN building.id IS '건물 ID';
COMMENT ON COLUMN building.name IS '건물 이름 (예: 북악관)';
COMMENT ON COLUMN building.max_floor IS '최고 층수';


-- =========================================================
-- room : 강의실/공간
-- =========================================================
CREATE TABLE room (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id  BIGINT      NOT NULL,
    code         VARCHAR(30) NOT NULL,
    number       VARCHAR(10) NOT NULL,
    floor        INT         NOT NULL,
    type         VARCHAR(15) NOT NULL,
    map_side     VARCHAR(6),
    map_order    INT,
    capacity     INT,
    sensor_level VARCHAR(5)  NOT NULL DEFAULT 'NONE',
    CONSTRAINT fk_room_building FOREIGN KEY (building_id) REFERENCES building (id),
    CONSTRAINT uk_room_code UNIQUE (code),
    CONSTRAINT uk_room_building_number UNIQUE (building_id, number),
    CONSTRAINT ck_room_type CHECK (type IN ('LECTURE', 'RESTROOM', 'ETC')),
    CONSTRAINT ck_room_map_side CHECK (map_side IN ('TOP', 'BOTTOM')),
    CONSTRAINT ck_room_sensor_level CHECK (sensor_level IN ('FULL', 'TH', 'NONE'))
);
-- building_id FK 인덱스는 uk_room_building_number(선두 컬럼)가 겸한다.

COMMENT ON TABLE room IS '강의실/공간';
COMMENT ON COLUMN room.id IS '공간 ID';
COMMENT ON COLUMN room.building_id IS '건물 ID';
COMMENT ON COLUMN room.code IS 'API 경로용 고유 코드 (예: bukak-617)';
COMMENT ON COLUMN room.number IS '호수 (예: 617, 화장실1)';
COMMENT ON COLUMN room.floor IS '층';
COMMENT ON COLUMN room.type IS '공간 종류 (LECTURE: 강의실, RESTROOM: 화장실, ETC: 기타)';
COMMENT ON COLUMN room.map_side IS '평면도 줄 위치 (TOP: 위, BOTTOM: 아래)';
COMMENT ON COLUMN room.map_order IS '평면도 줄 안에서의 순서 (왼쪽부터 1)';
COMMENT ON COLUMN room.capacity IS '수용 인원';
COMMENT ON COLUMN room.sensor_level IS '센서 수준 (FULL: CO2+온습도, TH: 온습도만, NONE: 없음)';


-- =========================================================
-- sensor_reading : 실내 센서 측정값
-- =========================================================
CREATE TABLE sensor_reading (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
