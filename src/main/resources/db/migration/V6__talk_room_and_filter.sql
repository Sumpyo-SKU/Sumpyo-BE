-- 캠퍼스톡: 글 대상 강의실(선택) + 근로생별 "연락 볼 구역" 필터(여러 개)

ALTER TABLE talk_post ADD COLUMN room_id BIGINT;
ALTER TABLE talk_post ADD CONSTRAINT fk_talk_post_room FOREIGN KEY (room_id) REFERENCES room (id);
CREATE INDEX idx_talk_post_room ON talk_post (room_id);
-- 목록: 내 건물 글 최신순
CREATE INDEX idx_talk_post_building_created ON talk_post (building_id, created_at);
COMMENT ON COLUMN talk_post.room_id IS '대상 강의실 ID (없으면 층 전체)';

-- =========================================================
-- member_talk_filter : 캠퍼스톡 연락 볼 구역 (목록 필터일 뿐 권한 아님)
-- =========================================================
CREATE TABLE member_talk_filter (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id BIGINT NOT NULL,
    floor     INT    NOT NULL,
    room_id   BIGINT,
    CONSTRAINT fk_member_talk_filter_member FOREIGN KEY (member_id) REFERENCES member (id),
    CONSTRAINT fk_member_talk_filter_room FOREIGN KEY (room_id) REFERENCES room (id),
    -- room_id NULL(층 전체)도 중복으로 본다 (PostgreSQL 15+)
    CONSTRAINT uk_member_talk_filter UNIQUE NULLS NOT DISTINCT (member_id, floor, room_id)
);
-- member_id FK 인덱스는 uk_member_talk_filter(선두 컬럼)가 겸한다.
CREATE INDEX idx_member_talk_filter_room ON member_talk_filter (room_id);

COMMENT ON TABLE member_talk_filter IS '캠퍼스톡 연락 볼 구역 (행이 없으면 건물 전체)';
COMMENT ON COLUMN member_talk_filter.id IS '필터 ID';
COMMENT ON COLUMN member_talk_filter.member_id IS '회원 ID';
COMMENT ON COLUMN member_talk_filter.floor IS '층';
COMMENT ON COLUMN member_talk_filter.room_id IS '강의실 ID (NULL 이면 그 층 전체, 값이 있으면 그 강의실만)';
