COMMENT ON COLUMN member.notify_ventilation IS '환기 알림 받기 (끄면 alert_enabled 와 상관없이 환기 알림 없음)';
COMMENT ON COLUMN member.notify_complaint IS '민원 알림 받기 (새 민원, 반복 민원)';
COMMENT ON COLUMN member.notify_sensor_error IS '센서 연결 끊김 알림 받기';

-- =========================================================
-- notification : 앱 안 알림함 (휴대폰 푸시 아님)
-- =========================================================
CREATE TABLE notification (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    member_id    BIGINT       NOT NULL,
    type         VARCHAR(30)  NOT NULL,
    room_id      BIGINT,
    action_id    BIGINT,
    complaint_id BIGINT,
    title        VARCHAR(100) NOT NULL,
    body         VARCHAR(200),
    dedup_key    VARCHAR(100) NOT NULL,
    read_at      TIMESTAMP,
    created_at   TIMESTAMP    NOT NULL,
    CONSTRAINT fk_notification_member FOREIGN KEY (member_id) REFERENCES member (id),
    CONSTRAINT fk_notification_room FOREIGN KEY (room_id) REFERENCES room (id),
    CONSTRAINT fk_notification_action FOREIGN KEY (action_id) REFERENCES action (id),
    CONSTRAINT fk_notification_complaint FOREIGN KEY (complaint_id) REFERENCES complaint (id),
    -- 같은 알림 중복 방지 (스캔이 여러 번 돌아도 한 번만)
    CONSTRAINT uk_notification_dedup UNIQUE (member_id, dedup_key),
    CONSTRAINT ck_notification_type CHECK (type IN
        ('VENTILATION_NOW', 'VENTILATION_SOON', 'REPEATED_COMPLAINT', 'NEW_COMPLAINT', 'SENSOR_ERROR'))
);
-- 알림함: 내 알림 최신순
CREATE INDEX idx_notification_member_created ON notification (member_id, created_at);
CREATE INDEX idx_notification_room ON notification (room_id);
CREATE INDEX idx_notification_action ON notification (action_id);
CREATE INDEX idx_notification_complaint ON notification (complaint_id);

COMMENT ON TABLE notification IS '앱 안 알림함';
COMMENT ON COLUMN notification.id IS '알림 ID';
COMMENT ON COLUMN notification.member_id IS '받는 사람 ID';
COMMENT ON COLUMN notification.type IS '종류 (VENTILATION_NOW: 지금 환기, VENTILATION_SOON: 곧 환기, REPEATED_COMPLAINT: 반복 민원, NEW_COMPLAINT: 새 민원, SENSOR_ERROR: 센서 끊김)';
COMMENT ON COLUMN notification.room_id IS '강의실 ID';
COMMENT ON COLUMN notification.action_id IS '조치 ID (누르면 조치 상세)';
COMMENT ON COLUMN notification.complaint_id IS '민원 ID (누르면 민원 상세)';
COMMENT ON COLUMN notification.title IS '제목';
COMMENT ON COLUMN notification.body IS '내용';
COMMENT ON COLUMN notification.dedup_key IS '중복 방지 키 (예: SOON:action:90, SENSOR:room:7:2026-10-21T14:00)';
COMMENT ON COLUMN notification.read_at IS '읽은 시각 (KST), 안 읽었으면 NULL';
COMMENT ON COLUMN notification.created_at IS '생성 시각 (KST)';
